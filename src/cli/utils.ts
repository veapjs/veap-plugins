import fs from "node:fs";
import path from "node:path";
import type { Output } from "@veap/kernel/cli";

function getVariableName(pkgName: string): string {
  const clean = pkgName
    .replace(/^@/, "")
    .replace(/\//, "-")
    .replace(/-plugin$/, "")
    .replace(/-module$/, "");

  // Special cases to match original naming if needed
  if (clean === "blog") return "BlogModulePlugin";
  if (clean === "panel") return "PanelModulePlugin";
  if (clean === "devtools") return "DevtoolsModulePlugin";
  if (clean === "backup") return "BackupModulePlugin";

  return (
    clean
      .split("-")
      .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
      .join("") + "Plugin"
  );
}

export interface RegeneratePluginsResult {
  filePath: string;
  plugins: Array<{ name: string; varName: string }>;
}

export function regeneratePluginsRegistry(
  rootDir: string,
  output?: Output,
): RegeneratePluginsResult {
  const pluginsFound: {
    name: string;
    varName: string;
  }[] = [];

  // 1. Scan package.json dependencies
  const pkgPath = path.join(rootDir, "package.json");
  if (fs.existsSync(pkgPath)) {
    const pkg = JSON.parse(fs.readFileSync(pkgPath, "utf-8"));
    const deps = {
      ...(pkg.dependencies || {}),
      ...(pkg.devDependencies || {}),
    };

    for (const depName of Object.keys(deps)) {
      let isPlugin = depName.endsWith("-plugin") && depName !== "@veap/cli";

      if (!isPlugin) {
        // Check node_modules package.json
        const depPkgPath = path.join(
          rootDir,
          "node_modules",
          depName,
          "package.json",
        );
        if (fs.existsSync(depPkgPath)) {
          try {
            const depPkg = JSON.parse(fs.readFileSync(depPkgPath, "utf-8"));
            if (depPkg.veap?.type === "plugin") {
              isPlugin = true;
            }
          } catch (_) {}
        }

        // Check plugins/ and modules/ local folders
        const cleanName = depName.replace(/^@[^/]+\//, "");
        const localPluginPkgPath = path.join(
          rootDir,
          "plugins",
          cleanName,
          "package.json",
        );
        const localModulePkgPath = path.join(
          rootDir,
          "modules",
          cleanName,
          "package.json",
        );

        for (const candidatePath of [localPluginPkgPath, localModulePkgPath]) {
          if (fs.existsSync(candidatePath)) {
            try {
              const depPkg = JSON.parse(
                fs.readFileSync(candidatePath, "utf-8"),
              );
              if (
                depPkg.veap?.type === "plugin" ||
                depPkg.veap?.type === "module"
              ) {
                isPlugin = true;
                break;
              }
            } catch (_) {}
          }
        }
      }

      if (isPlugin) {
        pluginsFound.push({
          name: depName,
          varName: getVariableName(depName),
        });
      }
    }
  }

  // Generate code for plugins.gen.ts
  let code =
    "/**\n * FILE AUTOMATICALLY GENERATED BY veap/cli\n * DO NOT EDIT THIS FILE MANUALLY!\n */\n\n";

  // Write imports
  for (const p of pluginsFound) {
    code += `import { default as ${p.varName} } from "${p.name}";\n`;
  }

  code += "\nexport const plugins = [\n";
  for (const p of pluginsFound) {
    code += `  ${p.varName},\n`;
  }
  code += "];\n";

  const pluginsGenPath = path.join(rootDir, "lib", "plugins.gen.ts");
  // Make sure lib/ directory exists
  const libDir = path.dirname(pluginsGenPath);
  if (!fs.existsSync(libDir)) {
    fs.mkdirSync(libDir, { recursive: true });
  }
  fs.writeFileSync(pluginsGenPath, code, "utf-8");

  const relativePath = path.relative(rootDir, pluginsGenPath);
  if (output) {
    output.info(
      `Regenerated ${relativePath} (${pluginsFound.length} plugin(s)).`,
    );
  } else {
    console.log(
      `[Veap CLI] Regenerated ${pluginsGenPath} with ${pluginsFound.length} plugins.`,
    );
  }

  return { filePath: pluginsGenPath, plugins: pluginsFound };
}

const WORKSPACE_MARKERS = [
  "pnpm-lock.yaml",
  "bun.lock",
  "bun.lockb",
  "yarn.lock",
  "package-lock.json",
  "pnpm-workspace.yaml",
];

function hasWorkspacesField(dir: string): boolean {
  const pkgPath = path.join(dir, "package.json");
  if (!fs.existsSync(pkgPath)) return false;
  try {
    const pkg = JSON.parse(fs.readFileSync(pkgPath, "utf-8"));
    const workspaces = pkg.workspaces;
    if (Array.isArray(workspaces) && workspaces.length > 0) return true;
    return (
      !!workspaces &&
      typeof workspaces === "object" &&
      Array.isArray((workspaces as { packages?: unknown }).packages) &&
      (workspaces as { packages: unknown[] }).packages.length > 0
    );
  } catch {
    return false;
  }
}

export function findProjectRoot(currentDir: string): string {
  if (
    WORKSPACE_MARKERS.some((marker) =>
      fs.existsSync(path.join(currentDir, marker)),
    ) ||
    hasWorkspacesField(currentDir)
  ) {
    return currentDir;
  }
  const parentDir = path.dirname(currentDir);
  if (parentDir === currentDir) {
    return process.cwd();
  }
  return findProjectRoot(parentDir);
}

export function processStubs(
  srcDir: string,
  destDir: string,
  variables: Record<string, string>,
) {
  if (!fs.existsSync(destDir)) {
    fs.mkdirSync(destDir, { recursive: true });
  }

  const entries = fs.readdirSync(srcDir, { withFileTypes: true });

  for (const entry of entries) {
    let destName = entry.name;
    for (const [key, value] of Object.entries(variables)) {
      destName = destName.replace(
        new RegExp("\\{\\{" + key + "\\}\\}", "g"),
        value,
      );
    }

    if (destName.endsWith(".stub")) {
      destName = destName.slice(0, -5);
    }

    const srcPath = path.join(srcDir, entry.name);
    const destPath = path.join(destDir, destName);

    if (entry.isDirectory()) {
      processStubs(srcPath, destPath, variables);
    } else {
      let content = fs.readFileSync(srcPath, "utf-8");
      for (const [key, value] of Object.entries(variables)) {
        content = content.replace(
          new RegExp("\\{\\{" + key + "\\}\\}", "g"),
          value,
        );
      }
      fs.writeFileSync(destPath, content);
    }
  }
}
